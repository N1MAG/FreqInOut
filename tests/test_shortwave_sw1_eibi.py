class _FakeEiBiResponse:
    def __init__(self, payload: bytes, *, url: str, content_type: str = "text/plain") -> None:
        self._payload = payload
        self._url = url
        self.status = 200
        self.headers = {
            "Content-Type": content_type,
            "Content-Length": str(len(payload)),
        }

    def __enter__(self) -> "_FakeEiBiResponse":
        return self

    def __exit__(self, *_args: object) -> None:
        return None

    def getcode(self) -> int:
        return self.status

    def geturl(self) -> str:
        return self._url

    def read(self, size: int = -1) -> bytes:
        if size < 0:
            size = len(self._payload)
        value, self._payload = self._payload[:size], self._payload[size:]
        return value


class _FakeEiBiOpener:
    def __init__(self, responses: dict[str, _FakeEiBiResponse]) -> None:
        self.responses = responses

    def open(self, request: object, *, timeout: float) -> _FakeEiBiResponse:
        del timeout
        url = str(getattr(request, "full_url"))
        return self.responses[url]


