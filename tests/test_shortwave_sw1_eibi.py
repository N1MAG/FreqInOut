def _store_module():
    for name in ("freqinout.core.shortwave_store", "freqinout.core.shortwave_dataset_store"):
        try:
            return importlib.import_module(name)
        except ModuleNotFoundError:
            continue
    pytest.fail("SW-1 must provide a Qt-free Shortwave dataset store")


def _store(path: Path):
    # SW-1 is additive but depends on the canonical resource-source registry.
    from freqinout.core.resource_catalog_models import CatalogSource
    from freqinout.core.resource_catalog_store import ResourceCatalogStore

    catalog = ResourceCatalogStore(path)
    catalog.create_schema()
    if catalog.get_source("eibi") is None:
        catalog.create_source(CatalogSource("eibi", "EiBi", "bundled", read_only=True))
    module = _store_module()
    store_type = getattr(module, "ShortwaveStore", None) or getattr(module, "ShortwaveDatasetStore", None)
    assert store_type is not None
    signature = inspect.signature(store_type)
    store = store_type(path) if len(signature.parameters) else store_type()
    create_schema = getattr(store, "create_schema", None) or getattr(store, "ensure_schema", None)
    assert callable(create_schema)
    create_schema()
    return store


def test_sw1_schema_is_additive_idempotent_and_exposes_bounded_read_api(tmp_path: Path) -> None:
    db_path = tmp_path / "freqinout_nets.db"
    _store(db_path)
    with sqlite3.connect(db_path) as conn:
        conn.execute("CREATE TABLE legacy_fixture (value TEXT NOT NULL)")
        conn.execute("INSERT INTO legacy_fixture(value) VALUES ('preserve me')")
    # Re-running startup-owned schema initialization is additive and leaves
    # unrelated legacy data untouched.
    store = _store(tmp_path / "freqinout_nets.db")
    with sqlite3.connect(db_path) as conn:
        tables = {row[0] for row in conn.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        preserved = conn.execute("SELECT value FROM legacy_fixture").fetchone()[0]
    assert {"resource_catalog_sources", "shortwave_datasets", "shortwave_entries"}.issubset(tables)
    assert preserved == "preserve me"
    assert callable(getattr(store, "list_entries", None) or getattr(store, "query_entries", None))
    query = getattr(store, "list_entries", None) or getattr(store, "query_entries")
    signature = inspect.signature(query)
    kwargs = {key: 200 for key in ("limit", "page_size") if key in signature.parameters}
    rows = query(**kwargs)
    assert len(rows) <= 200


