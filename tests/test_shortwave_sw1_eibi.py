def _field(value: object, *names: str, default: Any = None) -> Any:
    """Read a model field while allowing the implementation's DTO spelling."""

    if isinstance(value, Mapping):
        for name in names:
            if name in value:
                return value[name]
        return default
    for name in names:
        if hasattr(value, name):
            return getattr(value, name)
    return default


def _parser_module():
    for name in (
        "freqinout.core.shortwave_eibi",
        "freqinout.core.shortwave_provider",
        "freqinout.core.shortwave_parser",
        "freqinout.core.shortwave_eibi_provider",
    ):
        try:
            return importlib.import_module(name)
        except ModuleNotFoundError:
            continue
    pytest.fail("SW-1 must provide a Qt-free EiBi parser module")


def _parse_fixture(*, season_code: str = "A26", season_from: str | None = "2026-04-01T00:00:00Z", season_to: str | None = "2026-10-31T23:59:59Z") -> Any:
    module = _parser_module()
    raw = FIXTURE.read_bytes()
    readme = README_FIXTURE.read_bytes()
    adapter_type = getattr(module, "EiBiProviderAdapter", None)
    if adapter_type is not None:
        adapter = adapter_type()
        parse = getattr(adapter, "parse", None)
        if callable(parse):
            return parse(
                raw,
                readme,
                season_code=season_code,
                season_effective_from_utc=season_from,
                season_effective_to_utc=season_to,
            )
    parser_type = getattr(module, "EiBiParser", None)
    if parser_type is not None:
        signature = inspect.signature(parser_type)
        values = {
            "season_code": season_code,
            "season_effective_from_utc": season_from,
            "season_effective_to_utc": season_to,
            "encoding": "iso-8859-1",
        }
        parser = parser_type(**{key: value for key, value in values.items() if key in signature.parameters})
        for method_name, argument in (("parse_bytes", raw), ("parse", raw), ("parse_file", FIXTURE)):
            method = getattr(parser, method_name, None)
            if callable(method):
                return method(argument)

    function = getattr(module, "parse_eibi_csv", None)
    if callable(function):
        signature = inspect.signature(function)
        values = {
            "season_code": season_code,
            "season_effective_from_utc": season_from,
            "season_effective_to_utc": season_to,
            "encoding": "iso-8859-1",
        }
        kwargs = {key: value for key, value in values.items() if key in signature.parameters}
        for arguments in ((raw, readme), (raw, FIXTURE), (raw,)):
            try:
                return function(*arguments, **kwargs)
            except (TypeError, UnicodeDecodeError):
                continue
    pytest.fail("SW-1 EiBi parser must expose EiBiParser or parse_eibi_csv")


def _parse_bytes(raw: bytes, *, season_code: str = "A26") -> Any:
    """Invoke the parser with generated bytes for bounded-corpus checks."""

    module = _parser_module()
    readme = README_FIXTURE.read_bytes()
    adapter_type = getattr(module, "EiBiProviderAdapter", None)
    if adapter_type is not None:
        parse = getattr(adapter_type(), "parse", None)
        if callable(parse):
            return parse(
                raw,
                readme,
                season_code=season_code,
                season_effective_from_utc="2026-04-01T00:00:00Z",
                season_effective_to_utc="2026-10-31T23:59:59Z",
            )
    parser_type = getattr(module, "EiBiParser", None)
    if parser_type is not None:
        signature = inspect.signature(parser_type)
        kwargs = {
            key: value
            for key, value in {"season_code": season_code, "encoding": "iso-8859-1"}.items()
            if key in signature.parameters
        }
        parser = parser_type(**kwargs)
        method = getattr(parser, "parse_bytes", None) or getattr(parser, "parse", None)
        if callable(method):
            return method(raw)
    function = getattr(module, "parse_eibi_csv", None)
    if callable(function):
        signature = inspect.signature(function)
        kwargs = {
            key: value
            for key, value in {"season_code": season_code, "encoding": "iso-8859-1"}.items()
            if key in signature.parameters
        }
        return function(raw, readme, **kwargs)
    pytest.fail("SW-1 parser does not support bytes input")


def _entries(result: Any) -> list[Any]:
    for name in ("entries", "rows", "records", "schedule_entries"):
        value = _field(result, name)
        if value is not None:
            return list(value)
    if isinstance(result, (list, tuple)):
        return list(result)
    pytest.fail("EiBi parser result must expose bounded entries")


def _diagnostics(result: Any) -> list[Any]:
    value = _field(result, "diagnostics", "parse_diagnostics", default=())
    return list(value or ())


def _entry_by_station(entries: list[Any], text: str) -> Any:
    for entry in entries:
        if text in str(_field(entry, "station_name", "station", "name", default="")):
            return entry
    pytest.fail(f"fixture entry not found: {text}")


def test_fixture_preserves_audited_shape_and_latin1_decode() -> None:
    lines = FIXTURE.read_text(encoding="ascii").splitlines()
    assert len(lines[0].split(";")) == 12  # header has the documented trailing field
    assert all(len(line.split(";")) == 11 for line in lines[1:])

    # The fixture remains ASCII on disk so it is portable in source control;
    # substitute a genuine Latin-1 byte at the parser boundary.
    latin1 = FIXTURE.read_bytes().replace(b"BUE Latin-1", b"B\xfc Latin-1")
    assert b"\xfc" in latin1
    module = _parser_module()
    parser_type = getattr(module, "EiBiParser", None) or getattr(module, "EiBiProviderAdapter", None)
    assert parser_type is not None, "EiBiParser/EiBiProviderAdapter must own explicit encoding"
    signature = inspect.signature(parser_type)
    kwargs = {
        key: value
        for key, value in {"encoding": "iso-8859-1", "season_code": "A26"}.items()
        if key in signature.parameters
    }
    parser = parser_type(**kwargs)
    parse = getattr(parser, "parse_bytes", None) or getattr(parser, "parse", None)
    assert callable(parse)
    try:
        result = parse(latin1, README_FIXTURE.read_bytes(), season_code="A26", season_effective_from_utc="2026-04-01T00:00:00Z", season_effective_to_utc="2026-10-31T23:59:59Z")
    except TypeError:
        result = parse(latin1)
    station = _entry_by_station(_entries(result), "Latin-1")
    assert "ü" in str(_field(station, "station_name", "station", "name"))
    assert not any("decode" in str(_field(item, "reason", "message", default=item)).lower() for item in _diagnostics(result))


