def test_sw1_ten_thousand_row_query_remains_bounded(tmp_path: Path) -> None:
    store = _store(tmp_path / "freqinout_nets.db")
    from freqinout.core.shortwave_import import apply_shortwave_import, preview_shortwave_import

    header = FIXTURE.read_bytes().splitlines()[0]
    row = b"9955;0000-2400;Mo;USA;Synthetic bounded row;EN;NA;USA;1;;"
    raw = b"\n".join([header, *(row for _ in range(10_000))]) + b"\n"
    candidate = _parse_bytes(raw)
    apply_shortwave_import(store, preview_shortwave_import(store, candidate))
    current = store.current_dataset()
    assert current is not None
    assert current.record_count == 10_000
    with sqlite3.connect(store.db_path) as conn:
        persisted_count = conn.execute(
            "SELECT COUNT(*) FROM shortwave_entries WHERE dataset_key=?",
            (current.dataset_key,),
        ).fetchone()[0]
    assert persisted_count == 10_000
    query = getattr(store, "list_entries", None) or getattr(store, "query_entries", None)
    assert callable(query)
    signature = inspect.signature(query)
    kwargs = {key: value for key, value in {
        "limit": 200,
        "page_size": 200,
        "search": "Synthetic",
        "frequency_hz": 9_955_000,
    }.items() if key in signature.parameters}
    started = time.perf_counter()
    rows = query(**kwargs)
    elapsed = time.perf_counter() - started
    assert len(rows) <= 200
    assert rows, "bounded read API must query the imported 10,000-row dataset"
    assert elapsed < 0.100, f"bounded Shortwave query took {elapsed * 1000:.1f} ms"


